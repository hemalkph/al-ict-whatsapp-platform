// The pure execution engine (Phase 08B, V3.2 G and I.5; ADR 0018).
//
// `step(flow, session, event, context)` is a PURE function: no database, network, clock, randomness or environment. Time
// (`context.nowMs`) and the prompt token (`context.promptToken`) are injected by the caller. It never sends: it returns at
// most ONE declarative send effect per step (at most one request per session is ever in flight), and the runtime (08D/08E)
// decides whether and when that effect becomes an outbound request. It never writes or infers an outbound request state:
// `ACCEPTED`, `HELD`, ... are facts the runtime supplies.

// ----------------------------------------------------------------------------------------------------------------- types

/** Outbound request states as the runtime reports them (ADR 0014). The engine only reads them. */
export type RequestState =
  "QUEUED" | "SENDING" | "ACCEPTED" | "HELD" | "REJECTED" | "UNKNOWN_OUTCOME";

export type StudentInput =
  | { readonly kind: "text"; readonly text: string }
  | {
      readonly kind: "interactive";
      readonly subtype: "button_reply" | "list_reply";
      readonly replyId: string;
      /** True when the reply carries a context that does not match the prompt. A missing context changes nothing. */
      readonly contextMismatch?: boolean;
    }
  /** Anything else (an image, a location, a reaction, ...). Never an answer. */
  | { readonly kind: "other" };

export type EngineEvent =
  | { readonly type: "start" }
  /** The latest request of the session (identified by its step) reached a state. */
  | { readonly type: "send_result"; readonly stepSeq: number; readonly state: RequestState }
  /** A student message. `latestRequestState` is required while the session is WAITING_FOR_SEND (V3.2 G.3 step 3). */
  | {
      readonly type: "student_input";
      readonly input: StudentInput;
      readonly latestRequestState?: RequestState;
    }
  /** The runtime's idle sweep. `deliveryFailed`: the waiting prompt's message reported FAILED. */
  | { readonly type: "idle_expired"; readonly deliveryFailed?: boolean };

export type EngineContext = {
  /** Trusted current time, epoch milliseconds. */
  readonly nowMs: number;
  /** A fresh token for the prompt this step may produce (16 random bytes, base64url), generated by the runtime. */
  readonly promptToken?: string;
};

export type OutboundMessage =
  | { readonly kind: "text"; readonly text: string }
  | {
      readonly kind: "buttons";
      readonly body: string;
      readonly footer?: string;
      readonly buttons: readonly { readonly id: string; readonly title: string }[];
    }
  | {
      readonly kind: "list";
      readonly body: string;
      readonly buttonLabel: string;
      readonly footer?: string;
      readonly rows: readonly {
        readonly id: string;
        readonly title: string;
        readonly description?: string;
      }[];
    };

export type SendEffect = {
  readonly type: "SEND";
  /** The step that produced it: the runtime's `bot_step_seq`. */
  readonly stepSeq: number;
  readonly nodeId: string;
  /** The final message of an END / HANDOVER node (V3.2 I.5): the one request a terminal session may still dispatch. */
  readonly terminalNotice: boolean;
  readonly message: OutboundMessage;
};

export type EngineErrorCode =
  | "RENDER_REJECTED"
  | "STEP_TRANSITION_BUDGET"
  | "SESSION_TRANSITION_BUDGET"
  | "SEND_BUDGET"
  | "VARIABLE_STORAGE_BUDGET"
  | "VARIABLE_INVALID"
  | "PROMPT_TOKEN_INVALID"
  | "SESSION_INVALID"
  | "NODE_MISSING"
  | "CONTEXT_INVALID"
  | "FLOW_INVALID"
  | "ENGINE_INTERNAL";

export type InvalidReason =
  | "malformed_reply"
  | "stale_prompt"
  | "wrong_kind"
  | "unknown_option"
  | "context_mismatch"
  | "answer_invalid"
  | "not_waiting";

export type ReplyEvaluation =
  | {
      readonly result: "accepted";
      readonly next: string;
      readonly optionKey?: string;
      readonly value?: Literal;
    }
  | { readonly result: "duplicate" }
  | { readonly result: "invalid"; readonly reason: InvalidReason };

export type InputOutcome =
  | { readonly result: "accepted" }
  | { readonly result: "duplicate" }
  | { readonly result: "invalid"; readonly reason: InvalidReason; readonly attempts: number }
  /**
   * A request is in flight (still QUEUED / SENDING, or the next send queued by this step after a MESSAGE acceptance): not
   * evaluated, not counted; the runtime keeps the trigger and replays it once that request is accepted.
   */
  | { readonly result: "deferred"; readonly promptInteraction: boolean }
  /**
   * The session has ended (it was already terminal, or the step that applied a MESSAGE acceptance ended it), so nothing is
   * left to answer: ignored, not counted. An input that arrives during a MESSAGE send whose flow continues to another send is
   * `deferred`, never `not_awaited`.
   */
  | { readonly result: "not_awaited" }
  | { readonly result: "expired" };

export type StepOutcome =
  | SessionState
  /** Nothing to commit: the input is deferred while the latest request is in flight. */
  | "DEFERRED"
  /** Nothing to commit: the event does not apply (see `reason`). */
  | "IGNORED";

export type TraceEntry = {
  readonly nodeId: string;
  readonly type: NodeType;
  readonly reprompt?: true;
};

export type StepResult = {
  readonly outcome: StepOutcome;
  /** False when nothing changed and nothing needs to be committed. */
  readonly changed: boolean;
  readonly session: BotSession | null;
  /** At most one. */
  readonly effects: readonly SendEffect[];
  readonly input?: InputOutcome;
  /** Why the step went to the error node, or why an event was refused. */
  readonly error?: EngineErrorCode;
  /** Why an IGNORED event did not apply. */
  readonly reason?: string;
  /**
   * Why a configured final message was not produced: no send budget was left, or the session ended at the error node
   * because of an engine error (an error termination never carries a terminal notice, V3.2 G.4).
   */
  readonly noticeSkipped?: "SEND_BUDGET" | "ENGINE_ERROR";
  readonly renderFailures: readonly {
    readonly nodeId: string;
    readonly field: string;
    readonly reason: RenderFailure;
  }[];
  /** Nodes entered in this step, in order. */
  readonly trace: readonly TraceEntry[];
};

// ------------------------------------------------------------------------------------------------------- pure evaluators

const sameLiteral = (a: Literal, b: Literal): boolean =>
  typeof a === "string" && typeof b === "string"
    ? a.normalize("NFC") === b.normalize("NFC")
    : a === b;

/**
 * Evaluates a structured condition. A variable that is not set is seen only by `is_set`: every comparison on it is false,
 * `not_equals` included. Values of a different type never compare (no coercion; the validator already forbids it).
 */
export function evaluateCondition(
  condition: Condition,
  variables: Readonly<Record<string, Literal>>,
): boolean {
  switch (condition.op) {
    case "all":
      return condition.conditions.every((c) => evaluateCondition(c, variables));
    case "any":
      return condition.conditions.some((c) => evaluateCondition(c, variables));
    case "is_set":
      return Object.hasOwn(variables, condition.variable);
  }
  if (!Object.hasOwn(variables, condition.variable)) return false;
  const value = variables[condition.variable]!;
  switch (condition.op) {
    case "equals":
      return typeof value === typeof condition.value && sameLiteral(value, condition.value);
    case "not_equals":
      return typeof value === typeof condition.value && !sameLiteral(value, condition.value);
    case "in":
      return condition.values.some((v) => typeof v === typeof value && sameLiteral(value, v));
    case "lt":
      return typeof value === "number" && value < condition.value;
    case "gt":
      return typeof value === "number" && value > condition.value;
  }
}

const YES = ["yes", "y"];
const NO = ["no", "n"];
const INTEGER_TEXT = /^-?[0-9]{1,16}$/;

/** Parses a typed QUESTION answer; undefined when the text does not satisfy the answer's constraints. */
export function parseAnswer(answer: Answer, text: string): Literal | undefined {
  const trimmed = text.trim();
  switch (answer.kind) {
    case "text": {
      const value = trimmed.normalize("NFC");
      if (textProblem(value) !== null) return undefined;
      if (value.length < (answer.min ?? 1) || value.length > answer.max) return undefined;
      return value;
    }
    case "integer": {
      if (!INTEGER_TEXT.test(trimmed)) return undefined;
      const value = Number(trimmed) + 0; // `+ 0` turns -0 into 0
      if (!Number.isSafeInteger(value)) return undefined;
      if (answer.min !== undefined && value < answer.min) return undefined;
      if (answer.max !== undefined && value > answer.max) return undefined;
      return value;
    }
    case "yes_no": {
      const word = trimmed.toLowerCase();
      if (YES.includes(word)) return true;
      if (NO.includes(word)) return false;
      return undefined;
    }
  }
}

/**
 * Evaluates a student input against the session's pending prompt (V3.2 G.3 step 4). Pure: it changes nothing. The caller has
 * established that the latest request is ACCEPTED (the session is WAITING_FOR_INPUT).
 */
export function evaluateReply(
  flow: FlowConfig,
  session: BotSession,
  input: StudentInput,
): ReplyEvaluation {
  const awaiting = session.awaiting;
  const node = awaiting ? getNode(flow, awaiting.nodeId) : undefined;
  if (session.state !== "WAITING_FOR_INPUT" || !awaiting || !node || awaiting.phase !== "SENT")
    return { result: "invalid", reason: "not_waiting" };

  if (input.kind === "interactive") {
    const parsed = parseReplyId(input.replyId);
    if (!parsed) return { result: "invalid", reason: "malformed_reply" };
    if (parsed.promptToken === session.lastConsumedToken) return { result: "duplicate" };
    if (parsed.promptToken !== session.awaitingToken)
      return { result: "invalid", reason: "stale_prompt" };
    if (node.type !== "BUTTONS" && node.type !== "LIST")
      return { result: "invalid", reason: "wrong_kind" };
    if (input.subtype !== (node.type === "BUTTONS" ? "button_reply" : "list_reply"))
      return { result: "invalid", reason: "wrong_kind" };
    if (input.contextMismatch === true) return { result: "invalid", reason: "context_mismatch" };
    const option = node.options.find((o) => o.key === parsed.optionKey);
    if (!option || !awaiting.optionKeys.includes(parsed.optionKey))
      return { result: "invalid", reason: "unknown_option" };
    return { result: "accepted", next: option.next, optionKey: option.key };
  }
  if (input.kind === "text" && node.type === "QUESTION") {
    const value = parseAnswer(node.answer, input.text);
    if (value === undefined) return { result: "invalid", reason: "answer_invalid" };
    return { result: "accepted", next: node.next, value };
  }
  return { result: "invalid", reason: "wrong_kind" };
}

// ------------------------------------------------------------------------------------------------------------------ step

type Work = { -readonly [K in keyof BotSession]: BotSession[K] } & {
  variables: Record<string, Literal>;
};

class Run {
  readonly effects: SendEffect[] = [];
  readonly trace: TraceEntry[] = [];
  readonly renderFailures: StepResult["renderFailures"][number][] = [];
  error?: EngineErrorCode;
  noticeSkipped?: StepResult["noticeSkipped"];
  input?: InputOutcome;

  constructor(
    readonly flow: FlowConfig,
    readonly w: Work,
    readonly ctx: EngineContext,
  ) {}

  /** A committed step begins: runs nodes, re-prompts or ends the session. */
  begin(): void {
    this.w.stepSeq += 1;
  }

  result(): StepResult {
    return {
      outcome: this.w.state,
      changed: true,
      session: freeze(this.w),
      effects: this.effects,
      ...(this.input ? { input: this.input } : {}),
      ...(this.error ? { error: this.error } : {}),
      ...(this.noticeSkipped ? { noticeSkipped: this.noticeSkipped } : {}),
      renderFailures: this.renderFailures,
      trace: this.trace,
    };
  }

  /** Runs automatic nodes from `startId` until a send, a wait or a terminal node (V3.2 budgets apply). */
  advance(startId: string): void {
    let id = startId;
    for (let entered = 1; ; entered++) {
      const node = getNode(this.flow, id);
      if (!node) return this.fail("NODE_MISSING");
      if (entered > ENGINE_BUDGETS.transitionsPerStep) return this.fail("STEP_TRANSITION_BUDGET");
      if (this.w.transitionCount >= ENGINE_BUDGETS.transitionsPerSession)
        return this.fail("SESSION_TRANSITION_BUDGET");
      this.w.transitionCount += 1;
      this.w.currentNodeId = id;
      this.trace.push({ nodeId: id, type: node.type });

      switch (node.type) {
        case "MESSAGE": {
          const text = this.render(id, "text", node.text, FLOW_LIMITS.textMax);
          if (text === undefined) return;
          return this.send(id, { kind: "text", text }, null);
        }
        case "BUTTONS":
        case "LIST":
        case "QUESTION":
          this.w.invalidAttempts = 0;
          return this.prompt(id, node);
        case "CONDITION":
          id =
            node.branches.find((b) => evaluateCondition(b.when, this.w.variables))?.next ??
            node.else;
          continue;
        case "SET_VARIABLE":
          if (!this.store(node.variable, node.value)) return;
          id = node.next;
          continue;
        case "HANDOVER":
        case "END":
          return this.terminal(id, node);
      }
    }
  }

  /** Produces the prompt of an input-waiting node with a fresh token (also used to re-prompt after invalid input). */
  prompt(id: string, node: ButtonsNode | ListNode | QuestionNode): void {
    const token = this.ctx.promptToken;
    if (
      !isPromptToken(token) ||
      token === this.w.lastConsumedToken ||
      token === this.w.awaitingToken
    )
      return this.fail("PROMPT_TOKEN_INVALID");
    const message = this.promptMessage(id, node, token);
    if (message) this.send(id, message, token);
  }

  promptMessage(
    id: string,
    node: ButtonsNode | ListNode | QuestionNode,
    token: string,
  ): OutboundMessage | undefined {
    if (node.type === "QUESTION") {
      const text = this.render(id, "text", node.text, FLOW_LIMITS.textMax);
      return text === undefined ? undefined : { kind: "text", text };
    }
    const body = this.render(id, "body", node.body, FLOW_LIMITS.textMax);
    if (body === undefined) return undefined;
    let footer: string | undefined;
    if (node.footer !== undefined) {
      footer = this.render(id, "footer", node.footer, FLOW_LIMITS.footerMax);
      if (footer === undefined) return undefined;
    }
    const withFooter = footer === undefined ? {} : { footer };
    // Option keys are identifiers and the token was checked, so every id is well-formed.
    const replyId = (key: string) => formatReplyId(token, key)!;
    if (node.type === "BUTTONS")
      return {
        kind: "buttons",
        body,
        ...withFooter,
        buttons: node.options.map((o) => ({ id: replyId(o.key), title: o.title })),
      };
    return {
      kind: "list",
      body,
      buttonLabel: node.buttonLabel,
      ...withFooter,
      rows: node.options.map((o) => ({
        id: replyId(o.key),
        title: o.title,
        ...(o.description === undefined ? {} : { description: o.description }),
      })),
    };
  }

  /** Records the one send effect of this step and waits for the runtime to report its request's outcome. */
  send(id: string, message: OutboundMessage, token: string | null): void {
    if (this.w.sendCount >= ENGINE_BUDGETS.sendsPerSession) return this.fail("SEND_BUDGET");
    const node = getNode(this.flow, id)!;
    this.w.sendCount += 1;
    this.effects.push({
      type: "SEND",
      stepSeq: this.w.stepSeq,
      nodeId: id,
      terminalNotice: false,
      message,
    });
    this.w.state = "WAITING_FOR_SEND";
    this.w.awaiting = {
      nodeId: id,
      kind: node.type as Awaiting["kind"],
      phase: "QUEUED",
      optionKeys:
        node.type === "BUTTONS" || node.type === "LIST" ? node.options.map((o) => o.key) : [],
    };
    this.w.awaitingToken = token;
    this.w.expiresAt = null;
  }

  render(id: string, field: string, template: string, max: number): string | undefined {
    const rendered = renderText(template, this.w.variables, max);
    if (rendered.ok) return rendered.text;
    this.renderFailures.push({ nodeId: id, field, reason: rendered.reason });
    this.fail("RENDER_REJECTED");
    return undefined;
  }

  store(name: string, value: Literal): boolean {
    if (!fitsVariable(this.flow, name, value)) {
      this.fail("VARIABLE_INVALID");
      return false;
    }
    const next = { ...this.w.variables, [name]: value };
    if (variablesSize(next) > ENGINE_BUDGETS.variablesTotalMax) {
      this.fail("VARIABLE_STORAGE_BUDGET");
      return false;
    }
    this.w.variables = next;
    return true;
  }

  /**
   * END or HANDOVER: ends the session. On a flow transition a configured final message becomes the terminal notice; a
   * message that fails to render routes to the error node. An error termination (`error`) keeps its provenance
   * (`endReason = error`) and never carries a notice (V3.2 G.4 terminal-row rule), so it renders nothing and cannot recurse.
   */
  terminal(id: string, node: Extract<FlowNode, { type: "END" | "HANDOVER" }>, error = false): void {
    const w = this.w;
    w.currentNodeId = id;
    w.awaiting = null;
    w.awaitingToken = null;
    w.invalidAttempts = 0;
    w.expiresAt = null;
    w.state = node.type === "END" ? "COMPLETED" : "HANDED_OVER";
    w.endReason = error ? "error" : node.type === "END" ? "flow_end" : "flow_handover";
    w.handoverReason = node.type === "HANDOVER" ? (error ? "engine_error" : node.reason) : null;
    w.terminalNoticeStepSeq = null;
    if (node.message === undefined) return;
    if (error) {
      this.noticeSkipped = "ENGINE_ERROR";
      return;
    }
    if (w.sendCount >= ENGINE_BUDGETS.sendsPerSession) {
      this.noticeSkipped = "SEND_BUDGET";
      return;
    }
    const rendered = renderText(node.message, w.variables, FLOW_LIMITS.textMax);
    if (!rendered.ok) {
      this.renderFailures.push({ nodeId: id, field: "message", reason: rendered.reason });
      return this.fail("RENDER_REJECTED");
    }
    w.sendCount += 1;
    w.terminalNoticeStepSeq = w.stepSeq;
    this.effects.push({
      type: "SEND",
      stepSeq: w.stepSeq,
      nodeId: id,
      terminalNotice: true,
      message: { kind: "text", text: rendered.text },
    });
  }

  /**
   * Budget exceeded, unsafe rendered text or an inconsistent state: no send effect; the session ends at the error node as an
   * error termination (no terminal notice).
   */
  fail(code: EngineErrorCode): void {
    this.error = code;
    this.effects.length = 0;
    const errorNode = getNode(this.flow, this.flow.errorNodeId)!;
    this.trace.push({ nodeId: this.flow.errorNodeId, type: errorNode.type });
    this.terminal(
      this.flow.errorNodeId,
      errorNode as Extract<FlowNode, { type: "END" | "HANDOVER" }>,
      true,
    );
  }

  /** A system-decided end without a terminal notice (send outcome, idle expiry). */
  systemEnd(state: "COMPLETED" | "HANDED_OVER", endReason: EndReason, reason: string | null): void {
    const w = this.w;
    this.begin();
    w.state = state;
    w.endReason = endReason;
    w.handoverReason = reason;
    w.awaiting = null;
    w.awaitingToken = null;
    w.expiresAt = null;
  }

  /** The latest request was ACCEPTED: a prompt now waits for the student; a MESSAGE continues with its next node. */
  accepted(): void {
    const w = this.w;
    const awaiting = w.awaiting!;
    if (awaiting.kind === "MESSAGE") {
      const node = getNode(this.flow, awaiting.nodeId) as Extract<FlowNode, { type: "MESSAGE" }>;
      this.begin();
      w.awaiting = null;
      return this.advance(node.next);
    }
    w.state = "WAITING_FOR_INPUT";
    w.awaiting = { ...awaiting, phase: "SENT" };
    w.expiresAt = this.ctx.nowMs + this.flow.settings.idleTimeoutMinutes * 60_000;
  }

  /** HELD / REJECTED / UNKNOWN_OUTCOME (V3.2 G.4, N.1): handed over; the request itself is never touched. */
  sendFailed(state: "HELD" | "REJECTED" | "UNKNOWN_OUTCOME"): void {
    const reason =
      state === "HELD"
        ? "send_held"
        : state === "REJECTED"
          ? "send_rejected"
          : "send_outcome_unknown";
    this.systemEnd("HANDED_OVER", "system_handover", reason);
  }

  /** Applies a student input while WAITING_FOR_INPUT. */
  reply(input: StudentInput): void {
    const w = this.w;
    if (w.expiresAt !== null && this.ctx.nowMs >= w.expiresAt) {
      this.input = { result: "expired" };
      return this.systemEnd("COMPLETED", "idle_timeout", null);
    }
    const evaluation = evaluateReply(this.flow, freeze(w), input);
    if (evaluation.result === "duplicate") {
      this.input = { result: "duplicate" };
      return;
    }
    const node = getNode(this.flow, w.awaiting!.nodeId) as ButtonsNode | ListNode | QuestionNode;
    this.begin();
    if (evaluation.result === "accepted") {
      this.input = { result: "accepted" };
      w.lastConsumedToken = w.awaitingToken;
      w.awaitingToken = null;
      w.awaiting = null;
      w.invalidAttempts = 0;
      w.expiresAt = null;
      if (node.type === "QUESTION" && !this.store(node.variable, evaluation.value!)) return;
      return this.advance(evaluation.next);
    }
    const attempts = w.invalidAttempts + 1;
    this.input = { result: "invalid", reason: evaluation.reason, attempts };
    if (attempts >= this.flow.settings.maxInvalidAttempts) {
      w.awaiting = null;
      w.awaitingToken = null;
      w.invalidAttempts = 0;
      w.expiresAt = null;
      return this.advance(node.onInvalid);
    }
    w.invalidAttempts = attempts;
    this.trace.push({ nodeId: w.currentNodeId, type: node.type, reprompt: true });
    this.prompt(w.currentNodeId, node);
  }
}

function freeze(w: Work): BotSession {
  return {
    ...w,
    variables: { ...w.variables },
    ...(w.awaiting ? { awaiting: { ...w.awaiting } } : {}),
  };
}

const unchanged = (
  session: BotSession | null,
  outcome: "DEFERRED" | "IGNORED" | SessionState,
  extra: Partial<StepResult> = {},
): StepResult => ({
  outcome,
  changed: false,
  session,
  effects: [],
  renderFailures: [],
  trace: [],
  ...extra,
});

/** An input held back while a request is in flight; `promptInteraction` when it taps the pending prompt's token. */
function deferred(input: StudentInput, awaitingToken: string | null): InputOutcome {
  const parsed = input.kind === "interactive" ? parseReplyId(input.replyId) : null;
  return {
    result: "deferred",
    promptInteraction: parsed !== null && parsed.promptToken === awaitingToken,
  };
}

const NEW_SESSION: BotSession = {
  state: "WAITING_FOR_SEND",
  currentNodeId: "",
  variables: {},
  awaiting: null,
  awaitingToken: null,
  lastConsumedToken: null,
  stepSeq: 0,
  transitionCount: 0,
  sendCount: 0,
  invalidAttempts: 0,
  expiresAt: null,
  endReason: null,
  handoverReason: null,
  terminalNoticeStepSeq: null,
};

/**
 * Advances a session by one event. Never throws, never mutates its arguments, never sends: the returned effects are
 * declarations for the runtime. Given equal arguments it returns an equal result.
 */
export function step(
  flow: FlowConfig,
  session: BotSession | null,
  event: EngineEvent,
  context: EngineContext,
): StepResult {
  try {
    return run(flow, session, event, context);
  } catch {
    // Unexpected: fail closed. No effect; a live session ends FAILED (handing over would not be meaningful).
    if (!session) return unchanged(null, "FAILED", { error: "ENGINE_INTERNAL" });
    return {
      outcome: "FAILED",
      changed: true,
      session: {
        ...session,
        state: "FAILED",
        endReason: "error",
        awaiting: null,
        awaitingToken: null,
        expiresAt: null,
      },
      effects: [],
      error: "ENGINE_INTERNAL",
      renderFailures: [],
      trace: [],
    };
  }
}

function run(
  flow: FlowConfig,
  session: BotSession | null,
  event: EngineEvent,
  ctx: EngineContext,
): StepResult {
  if (!Number.isSafeInteger(ctx.nowMs) || ctx.nowMs < 0)
    return unchanged(session, "IGNORED", { reason: "context_invalid", error: "CONTEXT_INVALID" });
  const errorNode = getNode(flow, flow.errorNodeId);
  if (
    !errorNode ||
    (errorNode.type !== "END" && errorNode.type !== "HANDOVER") ||
    !getNode(flow, flow.startNodeId)
  )
    return unchanged(session, "IGNORED", { reason: "flow_invalid", error: "FLOW_INVALID" });

  if (event.type === "start") {
    if (session) return unchanged(session, "IGNORED", { reason: "session_exists" });
    const r = new Run(
      flow,
      { ...NEW_SESSION, currentNodeId: flow.startNodeId, variables: {} },
      ctx,
    );
    r.begin();
    r.advance(flow.startNodeId);
    return r.result();
  }
  if (!session) return unchanged(null, "IGNORED", { reason: "no_session" });
  if (isTerminalState(session.state)) {
    const extra: Partial<StepResult> = { reason: "session_ended" };
    if (event.type === "student_input")
      return unchanged(session, "IGNORED", { ...extra, input: { result: "not_awaited" } });
    return unchanged(session, "IGNORED", extra);
  }

  const r = new Run(flow, { ...session, variables: { ...session.variables } }, ctx);
  if (checkLiveSession(flow, session) !== null) {
    // Never trust the values of an inconsistent session, not even to render the error node's message.
    r.w.variables = {};
    r.w.awaiting = null;
    r.w.awaitingToken = null;
    r.begin();
    r.fail("SESSION_INVALID");
    return r.result();
  }

  switch (event.type) {
    case "send_result": {
      if (session.state !== "WAITING_FOR_SEND" || event.stepSeq !== session.stepSeq)
        return unchanged(session, "IGNORED", { reason: "stale_send_result" });
      if (event.state === "QUEUED" || event.state === "SENDING")
        return unchanged(session, "IGNORED", { reason: "request_in_flight" });
      if (event.state === "ACCEPTED") r.accepted();
      else r.sendFailed(event.state);
      return r.result();
    }
    case "idle_expired": {
      if (session.state !== "WAITING_FOR_INPUT")
        return unchanged(session, "IGNORED", { reason: "not_waiting_for_input" });
      if (session.expiresAt === null || ctx.nowMs < session.expiresAt)
        return unchanged(session, "IGNORED", { reason: "not_expired" });
      if (event.deliveryFailed === true)
        r.systemEnd("HANDED_OVER", "system_handover", "delivery_failed");
      else r.systemEnd("COMPLETED", "idle_timeout", null);
      return r.result();
    }
    case "student_input": {
      if (session.state === "WAITING_FOR_SEND") {
        const latest = event.latestRequestState;
        if (latest === undefined)
          return unchanged(session, "IGNORED", {
            reason: "request_state_required",
            error: "CONTEXT_INVALID",
          });
        if (latest === "QUEUED" || latest === "SENDING") {
          return unchanged(session, "DEFERRED", {
            input: deferred(event.input, session.awaitingToken),
          });
        }
        if (latest !== "ACCEPTED") {
          r.sendFailed(latest);
          r.input = { result: "not_awaited" };
          return r.result();
        }
        const wasMessage = session.awaiting!.kind === "MESSAGE";
        r.accepted();
        if (wasMessage) {
          // The input answers no MESSAGE, but it is not dropped: when the flow went on to another send it stays deferred
          // behind that request, exactly as if the acceptance had been reconciled before the input arrived. Only a session
          // that ended has nothing left to ask.
          r.input =
            r.w.state === "WAITING_FOR_SEND"
              ? deferred(event.input, r.w.awaitingToken)
              : { result: "not_awaited" };
          return r.result();
        }
      }
      r.reply(event.input);
      if (r.input?.result === "duplicate" && session.state === "WAITING_FOR_INPUT")
        return unchanged(session, "WAITING_FOR_INPUT", { input: r.input });
      return r.result();
    }
  }
}
