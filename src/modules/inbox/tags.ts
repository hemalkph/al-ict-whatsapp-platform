import { and, asc, eq, isNull, sql } from "drizzle-orm";
import { getDb, schema } from "@/db";
import { assertCan, revalidateActor, type AccessContext } from "@/modules/access";
import { NotFoundError, ValidationError } from "@/shared/errors/http-errors";
import { InboxConflictError } from "./errors";
import { safeLine } from "./display";
import type { InboxDeps } from "./list";
import { contactTagSchema, tagCreateSchema } from "./schemas";
import { uuid } from "./text";
import type { TagView } from "./types";

// Tags reuse the Phase 02 tables (tags, contact_tags). Two different capabilities, deliberately:
//   - attaching / detaching a tag on a contact: contact.edit
//   - defining a tag (creating one): tag.manage
// Tagging changes nothing else: no identity, alias, consent, lead or message is touched.

const view = (t: {
  id: string;
  name: string;
  color: string | null;
  archivedAt: Date | null;
}): TagView => ({
  id: t.id,
  name: safeLine(t.name, 40),
  color: t.color ? safeLine(t.color, 16) : null,
  archived: t.archivedAt !== null,
});

async function requireContact(
  db: NonNullable<InboxDeps["db"]>,
  organizationId: string,
  contactId: string,
) {
  if (!uuid.safeParse(contactId).success) throw new NotFoundError();
  const found = await db
    .select({ id: schema.contacts.id })
    .from(schema.contacts)
    .where(
      and(eq(schema.contacts.organizationId, organizationId), eq(schema.contacts.id, contactId)),
    );
  if (found.length === 0) throw new NotFoundError();
}

/** Tags that may be attached now: this organization's, not archived. */
export async function listAvailableTags(
  ctx: AccessContext,
  deps: InboxDeps = {},
): Promise<TagView[]> {
  assertCan(ctx, "contact.edit");
  const db = deps.db ?? getDb();
  const rows = await db
    .select()
    .from(schema.tags)
    .where(and(eq(schema.tags.organizationId, ctx.organizationId), isNull(schema.tags.archivedAt)))
    .orderBy(asc(sql`lower(${schema.tags.name})`), asc(schema.tags.id))
    .limit(200);
  return rows.map(view);
}

export async function createTag(
  ctx: AccessContext,
  rawInput: unknown,
  deps: InboxDeps = {},
): Promise<{ tag: TagView; created: boolean }> {
  assertCan(ctx, "tag.manage");
  const parsed = tagCreateSchema.safeParse(rawInput);
  if (!parsed.success) throw new ValidationError(["name"]);
  const name = parsed.data.name.trim();
  const db = deps.db ?? getDb();
  return db.transaction(async (tx) => {
    await revalidateActor(tx, ctx, "tag.manage");
    // The unique key is lower(btrim(name)) generated by PostgreSQL: "Maths" and " maths " are the same tag.
    const inserted = await tx
      .insert(schema.tags)
      .values({ organizationId: ctx.organizationId, name })
      .onConflictDoNothing()
      .returning();
    if (inserted[0]) return { tag: view(inserted[0]), created: true };
    const [existing] = await tx
      .select()
      .from(schema.tags)
      .where(
        and(
          eq(schema.tags.organizationId, ctx.organizationId),
          eq(schema.tags.nameKey, sql`lower(btrim(${name}))`),
        ),
      );
    if (!existing)
      throw new InboxConflictError("DUPLICATE", "That tag could not be created.", "tag");
    if (existing.archivedAt !== null)
      throw new InboxConflictError(
        "ARCHIVED",
        "A tag with that name exists but is archived.",
        "tag",
      );
    return { tag: view(existing), created: false };
  });
}

export async function addContactTag(
  ctx: AccessContext,
  contactId: string,
  rawInput: unknown,
  deps: InboxDeps = {},
): Promise<{ added: boolean }> {
  assertCan(ctx, "contact.edit");
  const parsed = contactTagSchema.safeParse(rawInput);
  if (!parsed.success) throw new ValidationError(["tagId"]);
  const db = deps.db ?? getDb();
  return db.transaction(async (tx) => {
    await revalidateActor(tx, ctx, "contact.edit");
    await requireContact(tx, ctx.organizationId, contactId);
    const [tag] = await tx
      .select({ id: schema.tags.id, archivedAt: schema.tags.archivedAt })
      .from(schema.tags)
      .where(
        and(
          eq(schema.tags.organizationId, ctx.organizationId),
          eq(schema.tags.id, parsed.data.tagId),
        ),
      );
    // A tag of another organization and a tag that does not exist are the same refusal.
    if (!tag) throw new ValidationError(["tagId"]);
    if (tag.archivedAt !== null)
      throw new InboxConflictError("ARCHIVED", "That tag is archived and cannot be added.", "tag");
    const inserted = await tx
      .insert(schema.contactTags)
      .values({ organizationId: ctx.organizationId, contactId, tagId: tag.id })
      .onConflictDoNothing()
      .returning({ tagId: schema.contactTags.tagId });
    return { added: inserted.length > 0 };
  });
}

export async function removeContactTag(
  ctx: AccessContext,
  contactId: string,
  tagId: string,
  deps: InboxDeps = {},
): Promise<{ removed: boolean }> {
  assertCan(ctx, "contact.edit");
  if (!uuid.safeParse(tagId).success) throw new ValidationError(["tagId"]);
  const db = deps.db ?? getDb();
  return db.transaction(async (tx) => {
    await revalidateActor(tx, ctx, "contact.edit");
    await requireContact(tx, ctx.organizationId, contactId);
    const removed = await tx
      .delete(schema.contactTags)
      .where(
        and(
          eq(schema.contactTags.organizationId, ctx.organizationId),
          eq(schema.contactTags.contactId, contactId),
          eq(schema.contactTags.tagId, tagId),
        ),
      )
      .returning({ tagId: schema.contactTags.tagId });
    return { removed: removed.length > 0 };
  });
}
